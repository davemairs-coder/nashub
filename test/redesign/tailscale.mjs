// Tailscale split (4.21.0): settings screen and a separate setup guide.
import { chromium } from 'playwright';
const base = process.argv[2] || 'http://127.0.0.1:8099/';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome' });
let fails = 0;
const ok = (n, p, d = '') => { if (!p) fails++; console.log((p ? 'PASS ' : 'FAIL ') + n + (d ? ' — ' + d : '')); };
const p = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage(); p.setDefaultTimeout(8000);
const errs = []; p.on('pageerror', e => errs.push(String(e))); p.on('dialog', d => { errs.push('dialog'); d.dismiss(); });
await p.goto(base, { waitUntil: 'networkidle' }); await p.waitForTimeout(300);
await p.evaluate(() => { skipOnboard(); S.apps = [{ id: 'jf', name: 'Jellyfin', emoji: '🎬', color: '#00A4DC', address: '100.64.0.5', port: '8096' }]; save(); go('manage'); go('mg-access'); });
await p.click('.mg-row:has-text("Tailscale")'); await p.waitForTimeout(120);
const v = () => p.evaluate(() => S.view);
ok('Access → Tailscale opens the settings screen', await v() === 'tailscale' && (await p.textContent('.pg-top .pg-title')).trim() === 'Tailscale');
ok('its back arrow goes to Access', await p.getAttribute('.pg-back', 'aria-label') === 'Back to Access');
ok('the how-to is not on this screen any more', !(await p.$('.ts-steps')) && (await p.$$('.mg-row:has(.ts-n)')).length === 4);
ok('the app on a Tailscale address is listed', /Jellyfin/.test(await p.textContent('.page')) && /100\.64\.0\.5/.test(await p.textContent('.page')));
await p.fill('#ts-host-inp', 'home-nas.tail2f9c.ts.net');
await p.click('.tog:has-text("https")'); await p.waitForTimeout(80);
ok('the protocol buttons say which is on', await p.getAttribute('.tog:has-text("https")', 'aria-pressed') === 'true');
await p.click('.mg-btn:has-text("Save hostname")'); await p.waitForTimeout(150);
ok('Save hostname saves it and says what Away will use', await p.evaluate(() => /home-nas/.test(S.tsHost)) && /home-nas\.tail2f9c\.ts\.net:PORT/.test(await p.textContent('.ts-ok')));
await p.fill('#home-ip-inp', '192.168.1.10'); await p.click('.mg-btn:has-text("Save home IP")'); await p.waitForTimeout(150);
ok('Save home IP saves it', await p.evaluate(() => S.homeIp === '192.168.1.10'));
await p.click('.mg-row:has(.ts-n) >> nth=2'); await p.waitForTimeout(120);
ok('a step opens the setup guide', await v() === 'tsguide' && (await p.textContent('.pg-top .pg-title')).trim() === 'Setup guide');
ok('the guide has the four steps as a numbered list and the tips', (await p.$$('.ts-steps > li')).length === 4 && /MagicDNS/.test(await p.textContent('.page')));
ok('the guide no longer promises a TS badge on tiles', !/TS badge/.test(await p.textContent('.page')));
await p.click('.pg-back'); await p.waitForTimeout(120);
ok('back from the guide returns to Tailscale', await v() === 'tailscale');
await p.evaluate(() => go('tsguide')); await p.waitForTimeout(80); await p.goBack(); await p.waitForTimeout(150);
ok('the phone back button also returns to Tailscale', await v() === 'tailscale');
await p.evaluate(() => { go('home'); openNetSheet(); }); await p.waitForTimeout(100);
await p.click('.net-sheet .sheet-link'); await p.waitForTimeout(120);
ok('"Tailscale settings" in the network chooser opens the settings screen', await v() === 'tailscale');
ok('no script errors or pop-ups', !errs.length, errs.slice(0, 2).join(' | '));
await b.close();
console.log(fails ? `${fails} FAILED` : 'ALL TAILSCALE CHECKS PASS'); process.exit(fails ? 1 : 0);
